using System.Diagnostics;
using ChainVote.Models;
using Microsoft.AspNetCore.Mvc;

namespace ChainVote.Controllers.ViewsController
{
    public class DefaultViewController : Controller
    {
        private readonly ILogger<DefaultViewController> _logger;

        public DefaultViewController(ILogger<DefaultViewController> logger)
        {
            _logger = logger;
        }

        public IActionResult Index()
        {
            return View();
        }

        public IActionResult Privacy()
        {
            return View();
        }

        public IActionResult About()
        {
            return View();
        }

        public IActionResult Elections()
        {
            return View();
        }

        public IActionResult Login()
        {
            return View();
        }

        public IActionResult Register()
        {
            return View();
        }

        [ResponseCache(Duration = 0, Location = ResponseCacheLocation.None, NoStore = true)]
        public IActionResult Error()
        {
            return View(new ErrorViewModel { RequestId = Activity.Current?.Id ?? HttpContext.TraceIdentifier });
        }
    }
}
